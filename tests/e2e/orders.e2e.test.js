describe('POST /api/orders/edit — order status update', () => {
  it('admin can change order status via edit endpoint', async () => {
    const res = await request
      .post('/api/orders/edit')
      .set(authAs('admin'))
      .send({ id: seeds.orderId, orderStatus: 'processing' });

    expectSuccess(res);
    expect(res.body.result.orderStatus).toBe('processing');

    // Restore
    await request
      .post('/api/orders/edit')
      .set(authAs('admin'))
      .send({ id: seeds.orderId, orderStatus: 'pending' });
  });

  it('admin can change payment status via edit endpoint', async () => {
    const res = await request
      .post('/api/orders/edit')
      .set(authAs('admin'))
      .send({ id: seeds.orderId, paymentStatus: 'confirmed' });

    expectSuccess(res);
    expect(res.body.result.paymentStatus).toBe('confirmed');

    // Restore
    await request
      .post('/api/orders/edit')
      .set(authAs('admin'))
      .send({ id: seeds.orderId, paymentStatus: 'pending' });
  });

  it('returns 401 without auth', async () => {
    const res = await request
      .post('/api/orders/edit')
      .send({ id: seeds.orderId, orderStatus: 'confirmed' });

    expectError(res, 401);
  });
});

