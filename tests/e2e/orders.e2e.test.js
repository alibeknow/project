describe('POST /api/orders/delete (orders:delete)', () => {
  let tempOrderId;

  beforeEach(async () => {
    const models = require('../../models');
    const tempOrder = await models.Order.create({
      refNo: `TEMP-DEL-${Date.now()}`,
      orderStatus: 'pending',
      paymentStatus: 'pending',
      paymentType: 'bankwire',
      declaredValue: 100,
      totalPrice: 100,
      companyPrice: 80,
      clientPrice: 100,
      contents: 'temp',
      pickupTime: new Date(Date.now() + 86400000),
      langCode: 'ru',
      countryCodeFrom: 'RU',
      countryCodeTo: 'KZ',
      addressFrom: 'Test',
      addressDetailsFrom: { city: 'Москва', province: '' },
      addressTo: 'Test',
      addressDetailsTo: { city: 'Алматы', province: '' },
      UserId: seeds.userIds.admin,
      CarrierId: seeds.carrierId,
      PackageTypeId: seeds.pkgBoxId,
      RateTypeId: seeds.rtStdId,
      CompanyId: seeds.companyId,
    });
    tempOrderId = tempOrder.id;
  });

  it('admin can delete an order', async () => {
    const res = await request
      .post('/api/orders/delete')
      .set(authAs('admin'))
      .send({ id: tempOrderId });

    expectSuccess(res);
    // orders/delete route returns true (uses obj.destroy() in a loop, not row count)
    expect(res.body.result).toBe(true);
  });

  it('returns 401 without auth', async () => {
    const res = await request
      .post('/api/orders/delete')
      .send({ id: tempOrderId });

    expectError(res, 401);
  });

  afterEach(async () => {
    const models = require('../../models');
    await models.Order.destroy({ where: { id: tempOrderId }, force: true }).catch(() => {});
  });
});

